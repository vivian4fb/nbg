const I18N_EN = {};       // captured from the HTML at boot
let I18N_CURRENT = "en";

(function captureEnglish() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.dataset.i18n;
    if (!(k in I18N_EN)) I18N_EN[k] = el.innerHTML.trim();
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const k = el.dataset.i18nPh;
    if (!(k in I18N_EN)) I18N_EN[k] = el.getAttribute("placeholder") || "";
  });
})();

/* translation lookup for JS-generated strings (used by main.js) */
window.T = function (key, fallback) {
  if (I18N_CURRENT !== "en" && I18N[I18N_CURRENT] && key in I18N[I18N_CURRENT])
    return I18N[I18N_CURRENT][key];
  return key in I18N_EN ? I18N_EN[key] : fallback;
};

function applyLang(code) {
  const dict = code === "en" ? I18N_EN : (I18N[code] || {});
  I18N_CURRENT = code;
  document.documentElement.lang = code;
  /* long-script languages need the compact nav sooner */
  if (["ta", "kn", "te", "ml"].includes(code)) document.documentElement.setAttribute("data-longnav", "1");
  else document.documentElement.removeAttribute("data-longnav");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.dataset.i18n;
    const val = k in dict ? dict[k] : I18N_EN[k];
    if (val === undefined) return;
    const isSvg = el.namespaceURI === "http://www.w3.org/2000/svg";
    if (!isSvg && /<|&\w+;/.test(val)) el.innerHTML = val;
    else el.textContent = val.replace(/<[^>]*>/g, "")
      .replace(/&lt;/g, "<").replace(/&gt;/g, ">")
      .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&");
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const k = el.dataset.i18nPh;
    const val = k in dict ? dict[k] : I18N_EN[k];
    if (val !== undefined) el.setAttribute("placeholder", val);
  });

  try { localStorage.setItem("oxyniti-lang", code); } catch (e) {}
  document.dispatchEvent(new CustomEvent("langchange", { detail: code }));
}

/* wire the dropdown + restore saved choice */
(function initLang() {
  const sel = document.getElementById("lang-select");
  if (!sel) return;
  let saved = "en";
  try { saved = localStorage.getItem("oxyniti-lang") || "en"; } catch (e) {}
  const urlLang = new URLSearchParams(location.search).get("lang");
  if (urlLang && (urlLang === "en" || I18N[urlLang])) saved = urlLang;
  if (saved !== "en" && I18N[saved]) { sel.value = saved; applyLang(saved); }
  sel.addEventListener("change", () => applyLang(sel.value));
})();
